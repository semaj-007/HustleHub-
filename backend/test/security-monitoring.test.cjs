const { test, before, after } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { randomBytes, randomUUID } = require('node:crypto');
const { Writable } = require('node:stream');
const request = require('supertest');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'hustlehub-security-'));
const metricsToken = randomBytes(32).toString('hex');
Object.assign(process.env, {
  NODE_ENV: 'test',
  JWT_SECRET: randomBytes(64).toString('hex'),
  MONITORING_TOKEN: metricsToken,
  BCRYPT_SALT_ROUNDS: '4',
  USER_STORE_PATH: path.join(directory, 'users.json'),
  MARKETPLACE_STORE_PATH: path.join(directory, 'marketplace.json'),
  AUTH_RATE_LIMIT_MAX: '100',
});
const app = require('../src/app')();
const repository = require('../src/modules/auth/user.repository');
const config = require('../src/config/env');
const logger = require('../src/config/logger');
const winston = require('winston');
let logs = '';
logger.transports.forEach((transport) => {
  transport.silent = true;
});
logger.level = 'info';
logger.add(
  new winston.transports.Stream({
    stream: new Writable({
      write(chunk, _encoding, done) {
        logs += chunk.toString();
        done();
      },
    }),
  }),
);
let owner, client, outsider, booking;
const password = 'SecretPassword123';
const signed = (operation, user) => operation.set('Authorization', `Bearer ${user.token}`);
async function register(name, role) {
  const res = await request(app)
    .post('/api/auth/register')
    .send({ name, role, email: `${name}@example.com`, password });
  assert.equal(res.status, 201);
  return res.body;
}
before(async () => {
  owner = await register('freelancer', 'freelancer');
  client = await register('client', 'client');
  outsider = await register('outsider', 'freelancer');
  const gig = await signed(request(app).post('/api/gigs'), owner).send({
    title: 'Secure listing for financial insight',
    description: 'A complete service for testing safe financial attribution.',
    category: 'design',
    priceCents: 250050,
    deliveryDays: 5,
  });
  const res = await signed(request(app).post('/api/bookings'), client)
    .set('Idempotency-Key', randomUUID())
    .send({ gigId: gig.body.gig.id });
  assert.equal(res.status, 201);
  booking = res.body;
});
after(() => fs.rmSync(directory, { recursive: true, force: true }));
test('financial insights are authenticated, freelancer-only, and strictly scoped', async () => {
  assert.equal((await request(app).get('/api/financial-insights')).status, 401);
  assert.equal((await signed(request(app).get('/api/financial-insights'), client)).status, 403);
  const res = await signed(request(app).get('/api/financial-insights'), owner);
  assert.equal(res.status, 200);
  assert.equal(res.body.insights.incomeCents, 250050);
  assert.equal(res.body.insights.taxCents, 50010);
  assert.equal(
    (
      await signed(
        request(app).get(`/api/financial-insights?freelancerId=${owner.user.id}`),
        outsider,
      )
    ).body.insights.incomeCents,
    0,
  );
  assert.equal(
    (await signed(request(app).get('/api/financial-insights?year=oops'), owner)).status,
    400,
  );
});
test('metrics require a separate valid credential and use low-cardinality labels', async () => {
  assert.equal((await request(app).get('/metrics')).status, 401);
  assert.equal((await signed(request(app).get('/metrics'), owner)).status, 401);
  const res = await request(app).get('/metrics').set('Authorization', `Bearer ${metricsToken}`);
  assert.equal(res.status, 200);
  assert.match(res.text, /hustlehub_http_requests_total/);
  assert.match(res.text, /hustlehub_security_events_total\{event="booking.confirmed"\} 1/);
  assert.match(res.text, /hustlehub_security_events_total\{event="transaction.created"\} 1/);
  assert.ok(!res.text.includes(owner.user.id));
  assert.ok(!res.text.includes(password));
});
test('request IDs are generated by the server and correlated with audit events', async () => {
  const res = await request(app).get('/api/health').set('X-Request-ID', 'spoofed-id');
  assert.match(res.headers['x-request-id'], /^[a-f0-9-]{36}$/);
  assert.notEqual(res.headers['x-request-id'], 'spoofed-id');
  assert.ok(logs.includes('booking.confirmed'));
  assert.ok(logs.includes('transaction.created'));
  assert.ok(logs.includes(booking.booking.id));
  logger.info('redaction.check', {
    password,
    nested: { authorization: 'secret-header', jwtSecret: 'secret-signing-key' },
  });
  assert.ok(!logs.includes(password));
  assert.ok(!logs.includes('secret-header'));
  assert.ok(!logs.includes('secret-signing-key'));
  assert.ok(!logs.includes(metricsToken));
});
test('readiness fails when persisted state is corrupt and recovers when restored', async () => {
  assert.equal((await request(app).get('/api/ready')).status, 200);
  const file = process.env.MARKETPLACE_STORE_PATH;
  const original = fs.readFileSync(file);
  try {
    fs.writeFileSync(file, '{invalid');
    const res = await request(app).get('/api/ready');
    assert.equal(res.status, 503);
    assert.deepEqual(res.body, { status: 'unavailable' });
  } finally {
    fs.writeFileSync(file, original);
  }
  assert.equal((await request(app).get('/api/ready')).status, 200);
});
test('server-side logout invalidates all issued tokens, survives app recreation, and permits new login', async () => {
  const second = await request(app)
    .post('/api/auth/login')
    .send({ email: 'client@example.com', password });
  assert.equal(second.status, 200);
  assert.equal((await signed(request(app).post('/api/auth/logout'), client)).status, 204);
  for (const token of [client.token, second.body.token]) {
    const anotherApp = require('../src/app')();
    assert.equal(
      (await request(anotherApp).get('/api/auth/me').set('Authorization', `Bearer ${token}`))
        .status,
      401,
    );
  }
  const fresh = await request(app)
    .post('/api/auth/login')
    .send({ email: 'client@example.com', password });
  assert.equal(fresh.status, 200);
  assert.equal((await signed(request(app).get('/api/auth/me'), fresh.body)).status, 200);
});
test('five failed logins lock an account, revoke tokens, and do not lock another account', async () => {
  const account = await register('locktest', 'client');
  for (let i = 0; i < config.lockout.maxFailures; i++)
    assert.equal(
      (
        await request(app)
          .post('/api/auth/login')
          .send({ email: 'locktest@example.com', password: 'WrongPassword123' })
      ).status,
      401,
    );
  const fileUser = JSON.parse(fs.readFileSync(process.env.USER_STORE_PATH)).find(
    (user) => user.id === account.user.id,
  );
  assert.ok(fileUser.lockedUntil > Date.now());
  assert.equal(fileUser.tokenVersion, 1);
  const locked = await request(app)
    .post('/api/auth/login')
    .send({ email: 'locktest@example.com', password });
  const missing = await request(app)
    .post('/api/auth/login')
    .send({ email: 'missing@example.com', password });
  assert.equal(locked.status, 401);
  assert.deepEqual(locked.body, missing.body);
  assert.equal((await signed(request(app).get('/api/auth/me'), account)).status, 401);
  assert.equal(
    (await request(app).post('/api/auth/login').send({ email: 'freelancer@example.com', password }))
      .status,
    200,
  );
  // Advance only the repository operation's clock to verify expiry without sleeping.
  const unlocked = await repository.recordLoginResult(
    account.user.id,
    true,
    fileUser.lockedUntil + 1,
  );
  assert.equal(unlocked.allowed, true);
  assert.equal(unlocked.user.failedLogins, 0);
  const recovered = await request(app)
    .post('/api/auth/login')
    .send({ email: 'locktest@example.com', password });
  assert.equal(recovered.status, 200);
  assert.ok(logs.includes('auth.locked'));
  assert.ok(logs.includes('auth.login_failed'));
  assert.ok(logs.includes('auth.login_succeeded'));
  assert.ok(logs.includes('auth.sessions_revoked'));
});

test('configured secret files take precedence and empty files fail closed', () => {
  const { spawnSync } = require('node:child_process');
  const secretFile = path.join(directory, 'signing-secret');
  const knownTestSecret = 'local-test-secret-not-a-production-credential';
  fs.writeFileSync(secretFile, knownTestSecret, { mode: 0o600 });
  const environment = { ...process.env, JWT_SECRET_FILE: secretFile };
  const script =
    "const c=require('./src/config/env');if(c.jwt.secret!=='local-test-secret-not-a-production-credential')process.exit(2)";
  const valid = spawnSync(process.execPath, ['-e', script], {
    cwd: path.resolve(__dirname, '..'),
    env: environment,
    encoding: 'utf8',
  });
  assert.equal(valid.status, 0);
  fs.writeFileSync(secretFile, '');
  const invalid = spawnSync(process.execPath, ['-e', script], {
    cwd: path.resolve(__dirname, '..'),
    env: environment,
    encoding: 'utf8',
  });
  assert.notEqual(invalid.status, 0);
  assert.match(invalid.stderr, /Missing required secret: JWT_SECRET/);
  assert.ok(!invalid.stderr.includes(process.env.JWT_SECRET));
});
